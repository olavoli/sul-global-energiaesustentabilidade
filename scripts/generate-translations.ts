import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve, basename } from "node:path";
import { parse } from "yaml";
import { format, resolveConfig } from "prettier";
import {
  translationLocales,
  translationSchema,
  type TranslationRecord,
} from "../src/content/translation-schema";
import type { ParsedEditorialFile } from "./generate-content";

/** Reuse the original MDX safety/schema checks; translations never enter the PT index. */
export async function generateTranslations(
  originals: readonly ParsedEditorialFile[],
  parseEditorial: (source: string, path: string) => ParsedEditorialFile,
  check: boolean,
): Promise<void> {
  const entries: { record: TranslationRecord; path: string }[] = [];
  const keys = new Set<string>();
  for (const locale of translationLocales) {
    const directory = resolve("content/translations", locale);
    let names: string[];
    try {
      names = await readdir(directory);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") continue;
      throw error;
    }
    for (const name of names.filter((n) => n.endsWith(".mdx")).sort()) {
      const path = `${directory}/${name}`;
      const source = await readFile(path, "utf8");
      const parsed = parseEditorial(source, path);
      const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
      if (!match) throw new Error(`Frontmatter ausente: ${path}`);
      const record = translationSchema.parse(parse(match[1]));
      if (record.locale !== locale || basename(name, ".mdx") !== record.slug)
        throw new Error(`Idioma/slug divergente: ${path}`);
      const original = originals.find((o) => o.frontmatter.slug === record.translationOf);
      if (!original || original.frontmatter.isDemo || original.frontmatter.status !== "published")
        throw new Error(`Original publicado ausente: ${path}`);
      const originalBytes = (await readFile(original.path, "utf8")).replace(/\r\n/g, "\n");
      if (createHash("sha256").update(originalBytes).digest("hex") !== record.sourceRevision)
        throw new Error(`Tradução desatualizada em relação ao original: ${path}`);
      const key = `${locale}:${record.translationOf}`;
      if (keys.has(key)) throw new Error(`Tradução duplicada: ${key}`);
      keys.add(key);
      if (
        record.author !== original.frontmatter.author ||
        record.category !== original.frontmatter.category ||
        record.isDemo ||
        record.sponsored !== original.frontmatter.sponsored
      )
        throw new Error(`Atribuição/classificação divergente: ${path}`);
      if (JSON.stringify(record.sources) !== JSON.stringify(original.frontmatter.sources))
        throw new Error(`Fontes estruturadas divergentes: ${path}`);
      const references = (body: string) =>
        body
          .split(/## (?:Referências|References|Referencias)\s*\n/)[1]
          ?.replace(/\r\n/g, "\n")
          .trim();
      if (
        record.referencesInBody !== original.frontmatter.referencesInBody ||
        references(parsed.body) !== references(original.body)
      )
        throw new Error(`Bibliografia deve preservar os registros originais: ${path}`);
      entries.push({ record, path: `../../../content/translations/${locale}/${name}` });
    }
  }
  const config = (await resolveConfig(resolve("src/content/generated/articles.ts"))) ?? {};
  const output = await format(
    `// Generated by scripts/generate-translations.ts. Do not edit manually.\nimport type { TranslationRecord } from "../translation-schema";\nimport type { MdxModuleLoader } from "../types";\nexport const translationRecords = ${JSON.stringify(
      entries.map((e) => e.record),
      null,
      2,
    )} as const satisfies readonly TranslationRecord[];\nexport const translationLoaders: Record<string, MdxModuleLoader> = {${entries.map((e) => `${JSON.stringify(`${e.record.locale}:${e.record.slug}`)}: () => import(${JSON.stringify(e.path)})`).join(",")}};\n`,
    { ...config, parser: "typescript" },
  );
  const target = resolve("src/content/generated/translations.ts");
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (current !== output) {
    if (check) throw new Error("Índice de traduções desatualizado.");
    await mkdir(resolve("src/content/generated"), { recursive: true });
    await writeFile(target, output);
  }
  console.log(
    `Traduções validadas: ${entries.length}; revisão humana/publicação são gates independentes.`,
  );
}
